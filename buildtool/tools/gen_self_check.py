#!/usr/bin/env python3
"""Generates buildtool/src/self_check.cpp from bank/src/validate.cpp.

usage: gen_self_check.py <repo root> [--check]
--check: exit 1 if the committed self_check.cpp differs (run by ctest).
"""
import sys
root = sys.argv[1]
check = len(sys.argv) > 2 and sys.argv[2] == '--check'
src = open(root + '/bank/src/validate.cpp').read()
lines = src.split('\n')
# body: from "namespace {" (line 16, index 15) up to the line before "}  // namespace" closing the anon ns
start = lines.index('namespace {')
end = lines.index('}  // namespace')
body = '\n'.join(lines[start + 1:end])
body = body.replace('detail::Crc32cFast(', 'Crc32cFast(')
body = body.replace('''  ViewAccess::File(*out) = d_;
  ViewAccess::Header(*out) = h_;
  std::memcpy(ViewAccess::Chunks(*out), chunks_, sizeof(chunks_));
  std::memcpy(static_cast<void*>(ViewAccess::Tables(*out)), tables_, sizeof(tables_));
  ViewAccess::Writable(*out) = false;
''', '')
body = body.replace('snd_result Run(const ParseOptions& opt, BankView* out) noexcept;', 'snd_result Run(const ParseOptions& opt) noexcept;')
body = body.replace('snd_result Checker::Run(const ParseOptions& opt, BankView* out) noexcept {', 'snd_result Checker::Run(const ParseOptions& opt) noexcept {')
assert 'ViewAccess' not in body and 'BankView' not in body
header = '''// GENERATED by buildtool/tools/gen_self_check.py from bank/src/validate.cpp.
// Do not edit; regenerate (ctest buildtool_self_check_in_sync fails when stale). buildtool may not depend on the bank module
// (CONTRACTS.md D-02), so the build re-checks every bank it writes with this
// copy of the runtime's validation rules, written against the contract's format
// definition only. Keep in sync with bank/src/validate.cpp: the shared
// corruption cases (bank/test/corruption_cases.hpp) run through both.
#include "self_check.hpp"

#include <cstdarg>
#include <cstdio>
#include <cstring>

#include "snd/format/bank_format.hpp"
#include "snd/types.h"

namespace snd::buildtool::detail {
namespace {

namespace bf = ::snd::bank_format;

// --- what the bank module's bank_view.hpp / validate.hpp provide -------------------------
inline constexpr std::uint32_t kKnownChunkCount =
    static_cast<std::uint32_t>(sizeof(bf::kChunks) / sizeof(bf::kChunks[0]));
constexpr int KnownChunkIndex(std::uint32_t fourcc) noexcept {
  for (std::uint32_t i = 0; i < kKnownChunkCount; ++i) {
    if (bf::kChunks[i].fourcc == fourcc) return static_cast<int>(i);
  }
  return -1;
}
constexpr std::uint32_t MaxKnownColumnsPerTable() noexcept {
  std::uint32_t m = 0;
  for (const bf::ChunkInfo& ch : bf::kChunks) {
    std::uint32_t n = 0;
    for (const bf::ColumnInfo& c : bf::kColumns) n += c.chunk == ch.fourcc ? 1u : 0u;
    if (n > m) m = n;
  }
  return m;
}
inline constexpr std::uint32_t kMaxTableColumns = MaxKnownColumnsPerTable();
constexpr const bf::ColumnInfo* FindColumnInfo(std::uint32_t chunk, std::uint32_t columnId) noexcept {
  for (const bf::ColumnInfo& c : bf::kColumns) {
    if (c.chunk == chunk && c.columnId == columnId) return &c;
  }
  return nullptr;
}
struct TableView {
  std::uint32_t rows = 0;
  std::uint32_t capacity = 0;
  void* columns[kMaxTableColumns] = {};
};
struct ChunkRef {
  const std::uint8_t* data = nullptr;
  std::uint64_t bytes = 0;
  std::uint16_t version = 0;
  std::uint16_t flags = 0;
};
struct ParseOptions {
  std::uint32_t platform = bf::kPlatformAny;
};
struct ParseError {
  snd_result code = SND_OK;
  std::uint32_t chunk = 0;
  std::uint32_t column = 0xFFFFFFFFu;
  std::uint32_t row = 0xFFFFFFFFu;
  char message[192] = {};
};
std::uint32_t Crc32cFast(std::uint32_t crc, const std::uint8_t* data, std::size_t n) noexcept {
  return bf::Crc32cUpdate(crc, data, n);
}

// --- copy of bank/src/validate.cpp (Checker) ----------------------------------------------
'''
footer = '''
}  // namespace

bool SelfCheckBank(const std::vector<std::uint8_t>& bank, std::string* why) {
  // The checker reads typed columns in place: give it a 64-byte aligned copy.
  std::vector<std::uint64_t> storage((bank.size() + 7) / 8 + 8);
  auto* base = reinterpret_cast<std::uint8_t*>(storage.data());
  while (reinterpret_cast<std::uintptr_t>(base) % 64 != 0) ++base;
  if (!bank.empty()) std::memcpy(base, bank.data(), bank.size());
  bf::FileHeader h{};
  if (bank.size() >= sizeof(h)) std::memcpy(&h, bank.data(), sizeof(h));
  ParseError err;
  Checker c(base, bank.size(), &err);
  ParseOptions opt;
  opt.platform = h.platform;  // the build's own platform tag
  if (c.Run(opt) == SND_OK) return true;
  if (why != nullptr) *why = err.message;
  return false;
}

}  // namespace snd::buildtool::detail
'''
out = header + body + footer
path = root + '/buildtool/src/self_check.cpp'
if check:
    current = open(path).read()
    if current != out:
        print('buildtool/src/self_check.cpp is stale: run buildtool/tools/gen_self_check.py <root>')
        sys.exit(1)
    sys.exit(0)
open(path, 'w').write(out)
